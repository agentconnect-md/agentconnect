/**
 * Pure dream-pipeline pieces (design: docs/designs/memory-dreaming.md §4–5):
 * the dream policy prompt, the untrusted-input prompt builder, and the
 * proposal parser/validator. All filesystem work lives in dream-runner.ts —
 * this module never touches disk, so it is testable byte-for-byte.
 *
 * The model returns a full proposed store as JSON; nothing here is applied
 * directly. The runner stages the validated result and the live store changes
 * only at explicit adoption (invariant: the model proposes, the daemon
 * disposes).
 */

export interface DreamProposalFile {
  path: string
  content: string
}

/** One mined skill candidate: a standard skill directory, staged for review.
 *  Never installed by the pipeline — see the design §7 (skills are the one
 *  dream output with NO auto-adopt path, because a skill is executable
 *  instruction content that steers every later session). */
export interface DreamProposalSkill {
  name: string
  description: string
  /** The SKILL.md body (frontmatter is generated by the daemon, not the model). */
  skill: string
  scripts: DreamProposalFile[]
  /** New structured form, deliberately limited to reviewable agent-local
   * SKILL.md + flat scripts. Legacy skill/scripts replies remain accepted. */
  files?: SkillBundleTextFile[]
  /** Sessions the procedure was observed in — validated against the mined set. */
  sessionIds: string[]
}

