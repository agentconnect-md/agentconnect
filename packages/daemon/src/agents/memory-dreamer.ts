/**
 * Recover the JSON object from a model reply.
 *
 * A mined skill body is itself Markdown, so it routinely contains fenced code
 * blocks — the whole point of a procedural skill is to show the commands. Those
 * inner fences sit inside a JSON string, but a lazy `` ```…``` `` match stops at
 * the first one and hands back a truncated object, which fails to parse and
 * loses the entire dream. So try the plausible readings in order and keep the
 * first that parses: the outermost fence, then a brace slice (correct when the
 * reply is a bare object, or a fence whose content is exactly the object), then
 * the innermost fence for a reply that trails prose after the JSON.
 */
function parseDreamJson(text: string): unknown | undefined {
  const candidates = [
    text.match(/```(?:json)?\s*([\s\S]*)```/i)?.[1],
    text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1),
    text.match(/```(?:json)?\s*([\s\S]*?)```/i)?.[1]
  ]
  for (const candidate of candidates) {
    if (!candidate) continue
    try {
      const value: unknown = JSON.parse(candidate)
      // A bare string or number parses but carries no proposal; keep looking.
      if (value && typeof value === 'object') return value
    } catch {
      // Not this reading — fall through to the next.
    }
  }
  return undefined
}

/**
 * Parse and harden the model's proposal. Returns null when the text carries no
 * usable JSON proposal (the dream then fails; partial staging is never written
 * from an unparseable reply). Individual entries are dropped, not repaired:
 * bad topic names, oversized bodies, duplicate paths, and index entries are
 * filtered the same way the distiller filters memories.
 */
export function parseDreamProposal(
  text: string,
  minedSessionIds: readonly string[] = [],
  trustedOrganizationKnowledge: readonly TrustedOrganizationKnowledgeTarget[] = [],
  trustedOrganizationSkills: readonly TrustedOrganizationSkillTarget[] = []
): DreamProposal | null {
  const value = parseDreamJson(text)
  if (value === undefined) return null
  const envelope = value as Record<string, unknown>
  const memory =
    envelope.agentMemory && typeof envelope.agentMemory === 'object'
      ? (envelope.agentMemory as Record<string, unknown>)
      : envelope
  if (typeof memory.index !== 'string' || !Array.isArray(memory.files)) return null

  const seen = new Set<string>([MEMORY_INDEX])
  const files: DreamProposalFile[] = []
  for (const row of memory.files) {
    const file = row as DreamProposalFile
    if (
      typeof file?.path !== 'string' ||
      typeof file?.content !== 'string' ||
      !TOPIC_RE.test(file.path) ||
      seen.has(file.path) ||
      !file.content.trim()
    ) {
      continue
    }
    seen.add(file.path)
    // Reserve one byte for the trailing newline so the final string is ≤ the
    // writer's byte cap, and clamp on a code-point boundary so the cut never
    // decodes to a replacement char that would push it back over the cap.
    const content = clampToBytesOnBoundary(file.content.trim(), MAX_MEMORY_FILE_BYTES - 1) + '\n'
    files.push({ path: file.path, content })
    if (files.length >= MAX_DREAM_FILES) break
  }

  const rawIndex = memory.index.trim()
  // A brand-new managed store legitimately has no index yet. Models commonly
  // represent that as an empty string even when they produced valid independent
  // organization proposals. Keep a blank store adoptable with a daemon-owned,
  // deterministic sentinel, but never paper over a blank index when topic files
  // exist (that would orphan substantive memory content on auto-adopt).
  if (!rawIndex && files.length > 0) return null
  const index = rawIndex
    ? clampToBytesOnBoundary(rawIndex, MAX_INDEX_INJECT_BYTES - 1)
    : '# Memory\n\n_No persistent memories yet._'
  return {
    files,
    index: index + '\n',
    skills: parseDreamSkills(envelope.agentSkills ?? envelope.skills, minedSessionIds),
    organizationKnowledge: parseOrganizationKnowledge(
      envelope.organizationKnowledge,
      minedSessionIds,
      trustedOrganizationKnowledge
    ),
    organizationSkills: parseOrganizationSkills(envelope.organizationSkills, minedSessionIds, trustedOrganizationSkills)
  }
}

function groundedSessions(value: unknown, minedSessionIds: readonly string[], minimum: number): string[] {
  if (!Array.isArray(value)) return []
  const mined = new Set(minedSessionIds)
  const sessions = [...new Set(value.filter((id): id is string => typeof id === 'string' && mined.has(id)))]
  return sessions.length >= minimum ? sessions : []
}

function recordOf(value: unknown): Record<string, unknown> | null {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null
}

function parseSkillFiles(value: unknown): SkillBundleTextFile[] {
  if (!Array.isArray(value) || value.length === 0 || value.length > MAX_SKILL_TREE_FILES) return []
  const files: SkillBundleTextFile[] = []
  const seen = new Set<string>()
  let expandedBytes = 0
  for (const entry of value) {
    const row = recordOf(entry)
    if (!row) return []
    const path = typeof row.path === 'string' ? row.path.normalize('NFC') : ''
    if (
      typeof row.path !== 'string' ||
      path !== row.path ||
      typeof row.content !== 'string' ||
      Buffer.byteLength(path, 'utf8') > 256 ||
      path.includes('\0') ||
      path.includes('\\') ||
      path.startsWith('/') ||
      /^[A-Za-z]:/.test(path) ||
      posix.normalize(path) !== path ||
      path
        .split('/')
        .some((segment) => !segment || segment === '.' || segment === '..' || Buffer.byteLength(segment) > 128) ||
      (row.encoding !== undefined && row.encoding !== 'utf8' && row.encoding !== 'base64')
    ) {
      return []
    }
    const encoding = row.encoding === 'base64' ? ('base64' as const) : ('utf8' as const)
    let bytes: Buffer
    if (encoding === 'base64') {
      if (
        row.content.length % 4 !== 0 ||
        !/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(row.content)
      ) {
        return []
      }
      bytes = Buffer.from(row.content, 'base64')
      if (bytes.toString('base64') !== row.content) return []
    } else {
      bytes = Buffer.from(row.content, 'utf8')
    }
    if (bytes.byteLength > MAX_SKILL_TREE_FILE_BYTES) return []
    expandedBytes += bytes.byteLength
    if (expandedBytes > MAX_SKILL_TREE_EXPANDED_BYTES) return []
    const key = path.toLocaleLowerCase('en-US')
    if (seen.has(key)) return []
    seen.add(key)
    files.push({ path, encoding, content: row.content })
  }
  for (const file of files) {
    const segments = file.path.split('/')
    for (let end = 1; end < segments.length; end += 1) {
      if (seen.has(segments.slice(0, end).join('/').toLocaleLowerCase('en-US'))) return []
    }
  }
  return files.some((file) => file.path === 'SKILL.md') ? files : []
}

/** Agent-local skill review still rides one legacy-sized response. Keep its
 * structured input to exactly what that surface renders and installs: one
 * UTF-8 SKILL.md plus a few flat UTF-8 scripts. Organization skills use the
 * full-tree parser above and the separate chunked review protocol. */
function parseAgentSkillFiles(value: unknown): SkillBundleTextFile[] {
  if (!Array.isArray(value) || value.length === 0 || value.length > MAX_SKILL_SCRIPTS + 1) return []
  const files: SkillBundleTextFile[] = []
  const seen = new Set<string>()
  for (const entry of value) {
    const row = recordOf(entry)
    if (!row || typeof row.path !== 'string' || typeof row.content !== 'string') return []
    const script = /^scripts\/([^/]+)$/.exec(row.path)
    const allowedPath = row.path === 'SKILL.md' || (script !== null && SKILL_SCRIPT_RE.test(script[1]!))
    if (
      !allowedPath ||
      (row.encoding !== undefined && row.encoding !== 'utf8') ||
      seen.has(row.path) ||
      !row.content.trim()
    ) {
      return []
    }
    const maxBytes = row.path === 'SKILL.md' ? MAX_SKILL_BODY_BYTES : MAX_SKILL_SCRIPT_BYTES
    if (Buffer.byteLength(row.content, 'utf8') > maxBytes) return []
    seen.add(row.path)
    files.push({ path: row.path, encoding: 'utf8', content: row.content })
  }
  return files.some((file) => file.path === 'SKILL.md') ? files : []
}

function skillManifest(files: readonly SkillBundleTextFile[]): { name: string; description: string } | null {
  const skillMd = files.find((file) => file.path === 'SKILL.md')
  if (!skillMd || skillMd.encoding !== 'utf8') return null
  const match = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(skillMd.content)
  if (!match) return null
  let value: unknown
  try {
    value = parseYaml(match[1]!, { maxAliasCount: 0 })
  } catch {
    return null
  }
  if (!value || typeof value !== 'object' || Array.isArray(value)) return null
  const manifest = value as Record<string, unknown>
  if (
    typeof manifest.name !== 'string' ||
    !SKILL_NAME_RE.test(manifest.name) ||
    typeof manifest.description !== 'string' ||
    !manifest.description.trim() ||
    manifest.description.length > 1024
  ) {
    return null
  }
  return { name: manifest.name, description: manifest.description.trim() }
}

export function parseOrganizationKnowledge(
  value: unknown,
  minedSessionIds: readonly string[],
  trustedTargets: readonly TrustedOrganizationKnowledgeTarget[] = []
): DreamOrganizationKnowledgeProposal[] {
  if (!Array.isArray(value)) return []
  const allowedUpdates = new Set(trustedTargets.map((target) => `${target.id.toLowerCase()}:${target.revision}`))
  const proposals: DreamOrganizationKnowledgeProposal[] = []
  for (const entry of value) {
    const row = recordOf(entry)
    if (!row) continue
    const operation = row.operation === 'update' ? ('update' as const) : row.operation === 'create' ? 'create' : null
    // `groundedSessionIds` appeared in a real Codex response after the former
    // prompt described "grounded sessionIds" without spelling the JSON key.
    // Accept that harmless compatibility alias, then apply the exact same
    // trusted-mined-set fence; invented citations still cannot pass.
    const sessions = groundedSessions(row.sessionIds ?? row.groundedSessionIds, minedSessionIds, 1)
    if (
      !operation ||
      sessions.length === 0 ||
      typeof row.title !== 'string' ||
      !row.title.trim() ||
      row.title.length > 128 ||
      typeof row.content !== 'string' ||
      !row.content.trim() ||
      Buffer.byteLength(row.content) > 262_144
    ) {
      continue
    }
    if (
      operation === 'update' &&
      (typeof row.targetId !== 'string' ||
        !UUID_RE.test(row.targetId) ||
        !Number.isInteger(row.targetRevision) ||
        Number(row.targetRevision) <= 0 ||
        !allowedUpdates.has(`${row.targetId.toLowerCase()}:${Number(row.targetRevision)}`))
    ) {
      continue
    }
    const tags = Array.isArray(row.tags)
      ? [
          ...new Set(
            row.tags.flatMap((tag) => {
              if (typeof tag !== 'string') return []
              const normalized = tag.trim()
              return normalized && normalized.length <= 64 ? [normalized] : []
            })
          )
        ].slice(0, 16)
      : []
    proposals.push({
      operation,
      ...(operation === 'update'
        ? { targetId: row.targetId as string, targetRevision: row.targetRevision as number }
        : {}),
      title: row.title.trim(),
      ...(typeof row.summary === 'string' && row.summary.length <= 1024 ? { summary: row.summary.trim() } : {}),
      tags,
      content: row.content,
      sessionIds: sessions
    })
    if (proposals.length >= MAX_ORGANIZATION_SUGGESTIONS) break
  }
  return proposals
}

export function parseOrganizationSkills(
  value: unknown,
  minedSessionIds: readonly string[],
  trustedTargets: readonly TrustedOrganizationSkillTarget[] = []
): DreamOrganizationSkillProposal[] {
  if (!Array.isArray(value)) return []
  const allowedUpdates = new Map<string, string>(
    trustedTargets.map((target) => [`${target.id.toLowerCase()}:${target.revision}`, target.name] as const)
  )
  const proposals: DreamOrganizationSkillProposal[] = []
  for (const entry of value) {
    const row = recordOf(entry)
    if (!row) continue
    const sessions = groundedSessions(row.sessionIds ?? row.groundedSessionIds, minedSessionIds, MIN_SKILL_SESSIONS)
    const files = parseSkillFiles(row.files)
    const title = typeof row.name === 'string' ? row.name : row.title
    const manifest = skillManifest(files)
    const operation = row.operation === 'update' ? ('update' as const) : row.operation === 'create' ? 'create' : null
    const updateKey =
      operation === 'update' && typeof row.targetId === 'string' && Number.isInteger(row.targetRevision)
        ? `${row.targetId.toLowerCase()}:${Number(row.targetRevision)}`
        : null
    if (
      !operation ||
      sessions.length === 0 ||
      typeof title !== 'string' ||
      !SKILL_NAME_RE.test(title) ||
      !manifest ||
      manifest.name !== title ||
      (operation === 'update' &&
        (typeof row.targetId !== 'string' ||
          !UUID_RE.test(row.targetId) ||
          !Number.isInteger(row.targetRevision) ||
          Number(row.targetRevision) <= 0 ||
          !updateKey ||
          allowedUpdates.get(updateKey) !== title)) ||
      Buffer.byteLength(
        JSON.stringify({
          kind: 'skill',
          files: [...files].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
        })
      ) > MAX_ORGANIZATION_SUGGESTION_BODY_BYTES
    ) {
      continue
    }
    proposals.push({
      operation,
      ...(operation === 'update'
        ? { targetId: row.targetId as string, targetRevision: row.targetRevision as number }
        : {}),
      title,
      summary: manifest.description,
      files,
      sessionIds: sessions
    })
    if (proposals.length >= MAX_ORGANIZATION_SUGGESTIONS) break
  }
  return proposals
}

/**
 * Validate mined skill candidates. Every rule here drops a candidate rather than
 * repairing it: a skill is executable instruction content a human is about to be
 * asked to install, so a malformed one is not worth guessing at.
 *
 * The grounding rule is the load-bearing one — a candidate must cite at least
 * {@link MIN_SKILL_SESSIONS} DISTINCT sessions FROM THE MINED SET. Citations the
 * model invented (or copied out of the untrusted transcript text) don't count,
 * which is what keeps recommendations anchored to trajectories that actually
 * happened rather than plausible-sounding inventions.
 */
export function parseDreamSkills(value: unknown, minedSessionIds: readonly string[]): DreamProposalSkill[] {
  if (!Array.isArray(value)) return []
  const mined = new Set(minedSessionIds)
  const seen = new Set<string>()
  const skills: DreamProposalSkill[] = []

  for (const row of value) {
    const record = recordOf(row)
    if (!record) continue
    const raw = record as Partial<DreamProposalSkill>
    const treeValue = record.files
    const tree = parseAgentSkillFiles(treeValue)
    const hasTree = Array.isArray(treeValue)
    const manifest = tree.length ? skillManifest(tree) : null
    const skillBody = typeof raw.skill === 'string' ? raw.skill : tree.find((file) => file.path === 'SKILL.md')?.content
    const description = manifest?.description ?? raw.description
    if (
      typeof raw?.name !== 'string' ||
      typeof description !== 'string' ||
      typeof skillBody !== 'string' ||
      !SKILL_NAME_RE.test(raw.name) ||
      (hasTree && tree.length === 0) ||
      (tree.length > 0 && (!manifest || manifest.name !== raw.name)) ||
      seen.has(raw.name) ||
      !description.trim() ||
      !skillBody.trim()
    ) {
      continue
    }

    // Grounding: only citations that name a session we actually mined.
    const cited = Array.isArray(raw.sessionIds)
      ? [...new Set(raw.sessionIds.filter((id): id is string => typeof id === 'string' && mined.has(id)))]
      : []
    if (cited.length < MIN_SKILL_SESSIONS) continue

    const scripts: DreamProposalFile[] = tree
      .filter((file) => file.path.startsWith('scripts/'))
      .map((file) => ({ path: file.path.slice('scripts/'.length), content: file.content }))
    if (tree.length === 0 && Array.isArray(raw.scripts)) {
      for (const entry of raw.scripts) {
        const script = entry as Partial<DreamProposalFile>
        if (
          typeof script?.path !== 'string' ||
          typeof script?.content !== 'string' ||
          !SKILL_SCRIPT_RE.test(script.path) ||
          scripts.some((s) => s.path === script.path) ||
          !script.content.trim()
        ) {
          continue
        }
        scripts.push({
          path: script.path,
          content: clampToBytesOnBoundary(script.content, MAX_SKILL_SCRIPT_BYTES)
        })
        if (scripts.length >= MAX_SKILL_SCRIPTS) break
      }
    }

    if (Buffer.byteLength(JSON.stringify({ skill: skillBody, scripts }), 'utf8') > MAX_AGENT_SKILL_REVIEW_JSON_BYTES) {
      continue
    }

    seen.add(raw.name)
    skills.push({
      name: raw.name,
      description: clampToBytesOnBoundary(description.trim(), 1024),
      skill: clampToBytesOnBoundary(skillBody.trim(), MAX_SKILL_BODY_BYTES),
      scripts,
      sessionIds: cited,
      ...(tree.length ? { files: tree } : {})
    })
    if (skills.length >= MAX_DREAM_SKILLS) break
  }
  return skills
}

/**
 * Content digest of a store's user-visible files (the adoption fence,
 * design §6). Dotfiles — the `.history` log — are excluded: provenance appends
 * must not invalidate a dream that changed nothing else.
 */
export function storeDigest(files: { name: string; content: string }[]): string {
  const hash = createHash('sha256')
  for (const file of [...files].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    if (file.name.startsWith('.')) continue
    hash.update(file.name)
    hash.update('\0')
    hash.update(file.content)
    hash.update('\0')
  }
  return `sha256:${hash.digest('hex')}`
}
